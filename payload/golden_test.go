// golden_test.go is the byte-compat gate for the public payload.Payload wire
// mirror. It proves the type round-trips byte-stably (unmarshal -> marshal ->
// unmarshal -> re-marshal is byte-identical) and that the first marshal matches
// the committed golden fixtures under testdata/ byte-for-byte.
//
// The fixtures are GENERATED from the live payload.Payload, never hand-edited:
// run `go test ./payload/ -run Golden -update` to regenerate them from the
// constructors below after any intentional struct change. The authoritative
// round-trip against the real wire model, and the regenerate-and-diff drift
// check, live outside this repository; this gate proves byte-stability and
// golden match only.
//
// The fixtures are opaque test data: RFC 5737 documentation addresses
// (192.0.2.0/24) and generic labels only, so they carry no real-world
// identifier.
package payload

import (
	"encoding/json"
	"flag"
	"os"
	"path/filepath"
	"strings"
	"testing"
)

// update regenerates the golden fixtures from the live constructors instead of
// comparing against them. The generated bytes are exactly what the Go type
// emits, which is the point: the fixtures stay a faithful mirror of the struct.
var update = flag.Bool("update", false, "regenerate payload golden fixtures from the live model")

const (
	goldenEmptyPath = "testdata/canonical_empty.json"
	goldenFullPath  = "testdata/canonical_full.json"
)

// canonicalBytes is the single serialization the fixtures and the gate agree
// on: two-space-indented JSON with a trailing newline. Using one function for
// both writing (-update) and comparing guarantees the fixtures are precisely
// what the type emits.
func canonicalBytes(t *testing.T, p Payload) []byte {
	t.Helper()
	b, err := json.MarshalIndent(p, "", "  ")
	if err != nil {
		t.Fatalf("marshal canonical payload: %v", err)
	}
	return append(b, '\n')
}

// buildCanonicalEmpty is the empty-but-strict-valid v8 payload: every required
// top-level slice present as [] and every additive scalar pointer null
// (including scan_status: a complete scan). This is
// exactly what NewEmpty followed by Normalize produces.
func buildCanonicalEmpty() Payload {
	p := NewEmpty("full", "engine/0.0.0")
	p.Normalize()
	return p
}

// buildCanonicalFull is a populated payload that exercises BOTH serialization
// boundaries at once:
//   - asset ip:192.0.2.10 carries SET scalar pointers (ip_address, mac_address)
//     AND NULL scalar pointers (os_guess trio) on the SAME object;
//   - asset ip:192.0.2.20 flips them (ip_address null, os_guess set);
//   - float64 confidence fields with long decimal expansions that would reveal
//     any precision/rounding/tie-break drift;
//   - a non-empty required slice (assets, service_exposures) alongside empty
//     required slices (identities, vulnerabilities, ... rendered []);
//   - a nested classification with its evidence map and security_flags present.
//
// All values are opaque: RFC 5737 documentation IPs and generic labels.
func buildCanonicalFull() Payload {
	p := NewEmpty("full", "engine/0.0.0")
	// v7: the full fixture exercises the SET scan_status boundary.
	p.ScanStatus = ptr(ScanStatusCancelled)
	p.ScanMetadata = &ScanMetadata{
		RecogDBVersion:       ptr("recog-2026.01"),
		OSSignatureDBVersion: ptr("osfp-v1"),
	}
	p.Assets = []AssetItem{
		{
			ExternalID:      "ip:192.0.2.10",
			Hostname:        "host-a",
			FQDN:            "host-a.example.test",
			IPAddress:       ptr("192.0.2.10"), // SET scalar pointer
			OperatingSystem: "generic-os",
			AssetType:       "server",
			Managed:         true,
			InternetFacing:  true,
			Services: []ServiceItem{
				{
					Port:                      443,
					Protocol:                  "tcp",
					ServiceName:               "https",
					ExposureLevel:             "internet",
					TLSVersion:                "TLSv1.3",
					ServiceVersion:            ptr("1.0.0"),
					Product:                   ptr("generic-httpd"),
					CPE:                       ptr("cpe:/a:example:generic-httpd:1.0.0"),
					ServiceIdentitySource:     ptr("fingerprint-db"),
					ServiceIdentityConfidence: ptr(0.9876543210987654), // precision
				},
				{
					Port:          22,
					Protocol:      "tcp",
					ServiceName:   "ssh",
					ExposureLevel: "internal",
					// every v5/v6 scalar pointer left nil -> null (unset boundary)
				},
			},
			Classification: &ClassificationEvidence{
				AssetType:     "server",
				Confidence:    0.123456789012345, // precision
				RuleName:      "open_ports.web",
				Evidence:      map[string]string{"method": "heuristic", "open_ports": "443,22"},
				SecurityFlags: []string{"internet_exposed_service"},
			},
			NetworkAliases: []NetworkAliasItem{
				{Hostname: "host-a-alt", Address: "192.0.2.11"},
			},
			MACAddress: ptr("02:00:5e:10:00:10"), // SET scalar pointer
			MACVendor:  ptr("generic-vendor"),    // SET scalar pointer
			// os_guess trio left nil -> null, on the SAME object as the set pointers
			OSBuild:      ptr("10.0.20348"), // v8: SET
			UBR:          ptr(int64(4294)),
			InstalledKbs: &InstalledKbs{Status: InstalledKbsCollected, Kbs: []string{"KB5066782", "KB890830"}},
		},
		{
			ExternalID:        "ip:192.0.2.20",
			Hostname:          "host-b",
			FQDN:              "host-b.example.test",
			IPAddress:         nil, // NULL scalar pointer (flipped from host-a)
			OperatingSystem:   "generic-os",
			AssetType:         "workstation",
			OSGuess:           ptr("generic-linux"), // SET scalar pointer
			OSGuessSource:     ptr("osfp-ttl"),
			OSGuessConfidence: ptr(0.8675309), // precision + SET
			// Services / NetworkAliases left nil -> Normalize forces []
			// v8: os_build and ubr left nil -> null; kbs left nil -> Normalize forces [].
			InstalledKbs: &InstalledKbs{Status: InstalledKbsUnavailable},
		},
	}
	p.ServiceExposures = []ServiceExposureItem{
		{
			AssetExternalID:           "ip:192.0.2.10",
			Port:                      443,
			Protocol:                  "tcp",
			ServiceName:               "https",
			ExposureLevel:             "internet",
			TLSVersion:                "TLSv1.3",
			ServiceVersion:            ptr("1.0.0"),
			Product:                   ptr("generic-httpd"),
			CPE:                       ptr("cpe:/a:example:generic-httpd:1.0.0"),
			ServiceIdentitySource:     ptr("fingerprint-db"),
			ServiceIdentityConfidence: ptr(0.9876543210987654),
		},
	}
	// identities, vulnerabilities, configuration_checks, password_policies,
	// software_inventory, missing_kbs, tls_probes stay [] (empty required slice).
	p.Normalize()
	return p
}

// goldenCase pairs a fixture path with the live constructor that regenerates it.
type goldenCase struct {
	name         string
	path         string
	buildPayload func() Payload
}

func goldenCases() []goldenCase {
	return []goldenCase{
		{name: "empty", path: goldenEmptyPath, buildPayload: buildCanonicalEmpty},
		{name: "full", path: goldenFullPath, buildPayload: buildCanonicalFull},
	}
}

// TestGoldenMatch asserts each fixture equals the bytes the live payload.Payload
// emits (golden match). Under -update it regenerates the fixtures instead. This
// is the fixtures-are-generated-never-hand-edited contract.
func TestGoldenMatch(t *testing.T) {
	for _, tc := range goldenCases() {
		tc := tc
		t.Run(tc.name, func(t *testing.T) {
			want := canonicalBytes(t, tc.buildPayload())

			if *update {
				if err := os.MkdirAll(filepath.Dir(tc.path), 0o755); err != nil {
					t.Fatalf("mkdir testdata: %v", err)
				}
				if err := os.WriteFile(tc.path, want, 0o644); err != nil {
					t.Fatalf("write golden %s: %v", tc.path, err)
				}
				t.Logf("regenerated %s (%d bytes)", tc.path, len(want))
				return
			}

			golden, err := os.ReadFile(tc.path)
			if err != nil {
				t.Fatalf("read golden %s (run `go test ./payload/ -run Golden -update` to generate): %v", tc.path, err)
			}
			if string(golden) != string(want) {
				t.Errorf("golden mismatch for %s: the live payload.Payload no longer marshals to the committed fixture.\n--- live ---\n%s\n--- golden ---\n%s", tc.path, want, golden)
			}
		})
	}
}

// TestGoldenRoundTripStable proves byte-stability: for each fixture,
// unmarshal(golden) -> marshal -> unmarshal -> re-marshal yields bytes identical
// to the first marshal, and the first marshal equals the committed golden. A
// serialization change that is not byte-stable (e.g. a non-deterministic map or
// a lossy pointer flip) reddens here.
func TestGoldenRoundTripStable(t *testing.T) {
	for _, tc := range goldenCases() {
		tc := tc
		t.Run(tc.name, func(t *testing.T) {
			if *update {
				t.Skip("skipping round-trip under -update")
			}
			golden, err := os.ReadFile(tc.path)
			if err != nil {
				t.Fatalf("read golden %s: %v", tc.path, err)
			}

			var p1 Payload
			if err := json.Unmarshal(golden, &p1); err != nil {
				t.Fatalf("unmarshal golden %s: %v", tc.path, err)
			}
			first := canonicalBytes(t, p1)
			if string(first) != string(golden) {
				t.Fatalf("unmarshal(golden)->marshal != golden for %s; serialization is not byte-stable", tc.path)
			}

			var p2 Payload
			if err := json.Unmarshal(first, &p2); err != nil {
				t.Fatalf("second unmarshal %s: %v", tc.path, err)
			}
			second := canonicalBytes(t, p2)
			if string(second) != string(first) {
				t.Errorf("round-trip not byte-stable for %s: first marshal != second marshal", tc.path)
			}
		})
	}
}

// TestGoldenNullVsEmptyAndPrecision pins the LIB-05 boundaries on the populated
// fixture: unset scalar pointer -> null, set scalar pointer -> value, empty
// required slice -> [] (never null), and float64 confidence survives round-trip
// with no decimal drift.
//
// These assertions also make the gate redden on the two struct regressions the
// discipline forbids, WITHOUT regressing the struct here:
//   - adding `omitempty` to a required slice would drop/null it, so the
//     `"identities": []` assertion (and the byte-for-byte golden match) fails;
//   - de-pointering an additive scalar (e.g. os_guess *string -> string) would
//     emit `""` instead of `null` for an unset value, so the `"os_guess": null`
//     assertion (and the golden match) fails.
func TestGoldenNullVsEmptyAndPrecision(t *testing.T) {
	if *update {
		t.Skip("skipping boundary assertions under -update")
	}
	golden, err := os.ReadFile(goldenFullPath)
	if err != nil {
		t.Fatalf("read golden %s: %v", goldenFullPath, err)
	}

	var p Payload
	if err := json.Unmarshal(golden, &p); err != nil {
		t.Fatalf("unmarshal golden: %v", err)
	}
	remarshalled := string(canonicalBytes(t, p))

	if len(p.Assets) != 2 {
		t.Fatalf("expected 2 assets in full fixture, got %d", len(p.Assets))
	}
	a0, a1 := p.Assets[0], p.Assets[1]

	// Unset scalar pointer -> null (os_guess trio on asset 0, ip_address on asset 1).
	if a0.OSGuess != nil {
		t.Errorf("asset[0].OSGuess should be nil (unset), got %q", *a0.OSGuess)
	}
	if a1.IPAddress != nil {
		t.Errorf("asset[1].IPAddress should be nil (unset), got %q", *a1.IPAddress)
	}
	for _, want := range []string{`"os_guess": null`, `"os_guess_source": null`, `"os_guess_confidence": null`} {
		if !strings.Contains(remarshalled, want) {
			t.Errorf("unset scalar pointer did not re-marshal to %q; a de-pointered additive scalar would fail here", want)
		}
	}

	// Set scalar pointer -> value (ip_address + mac on asset 0, os_guess on asset 1).
	if a0.IPAddress == nil || *a0.IPAddress != "192.0.2.10" {
		t.Errorf("asset[0].IPAddress round-trip = %v, want 192.0.2.10", a0.IPAddress)
	}
	if a0.MACAddress == nil || *a0.MACAddress != "02:00:5e:10:00:10" {
		t.Errorf("asset[0].MACAddress lost in round-trip: %v", a0.MACAddress)
	}
	for _, want := range []string{`"ip_address": "192.0.2.10"`, `"mac_address": "02:00:5e:10:00:10"`, `"os_guess": "generic-linux"`} {
		if !strings.Contains(remarshalled, want) {
			t.Errorf("set scalar pointer did not re-marshal to %q", want)
		}
	}

	// Empty required slice -> [] (never null). These top-level required slices
	// were left empty; an `omitempty` regression would drop or null them.
	for _, tag := range []string{
		"identities", "vulnerabilities", "configuration_checks",
		"password_policies", "software_inventory", "missing_kbs", "tls_probes",
	} {
		wantEmpty := `"` + tag + `": []`
		wantNull := `"` + tag + `": null`
		if !strings.Contains(remarshalled, wantEmpty) {
			t.Errorf("empty required slice %q did not re-marshal to []; an omitempty regression would fail here", tag)
		}
		if strings.Contains(remarshalled, wantNull) {
			t.Errorf("empty required slice %q re-marshalled to null (strict-model 400 trap)", tag)
		}
	}
	// A nested empty required slice forced by Normalize must also be [] not null
	// (asset[1].services was left nil before Normalize).
	if len(a1.Services) != 0 {
		t.Errorf("asset[1].Services should be empty, got %d", len(a1.Services))
	}

	// float64 precision: confidence values survive round-trip with no drift.
	if a1.OSGuessConfidence == nil || *a1.OSGuessConfidence != 0.8675309 {
		t.Errorf("os_guess_confidence precision drift: got %v, want 0.8675309", a1.OSGuessConfidence)
	}
	if a0.Classification == nil || a0.Classification.Confidence != 0.123456789012345 {
		t.Errorf("classification confidence precision drift: got %v, want 0.123456789012345", a0.Classification)
	}
	if len(a0.Services) == 0 || a0.Services[0].ServiceIdentityConfidence == nil || *a0.Services[0].ServiceIdentityConfidence != 0.9876543210987654 {
		t.Errorf("service_identity_confidence precision drift on asset[0].services[0]")
	}
	for _, want := range []string{
		`"os_guess_confidence": 0.8675309`,
		`"confidence": 0.123456789012345`,
		`"service_identity_confidence": 0.9876543210987654`,
	} {
		if !strings.Contains(remarshalled, want) {
			t.Errorf("float64 field did not re-marshal byte-stably as %q", want)
		}
	}

	// v8 asset fields: set values, unset null, and kbs [] when the object exists.
	for _, want := range []string{
		`"os_build": "10.0.20348"`,
		`"ubr": 4294`,
		`"os_build": null`,
		`"ubr": null`,
		`"status": "collected"`,
		`"status": "unavailable"`,
		`"kbs": []`,
	} {
		if !strings.Contains(remarshalled, want) {
			t.Errorf("v8 asset field did not re-marshal as %q", want)
		}
	}
	if strings.Contains(remarshalled, `"kbs": null`) {
		t.Error("kbs re-marshalled to null")
	}

	// Nested classification evidence map + security_flags present (not null).
	if a0.Classification == nil || len(a0.Classification.Evidence) == 0 || len(a0.Classification.SecurityFlags) == 0 {
		t.Errorf("asset[0] classification evidence/security_flags lost in round-trip: %+v", a0.Classification)
	}
}
